SAMPLE_COURSE = """# AI 应用开发课程资料

## 检索增强生成（RAG）基础

检索增强生成（RAG）先从外部知识库检索与问题相关的资料片段，再把这些片段放入大语言模型的上下文，让模型基于资料生成回答。RAG 的核心价值是补充模型训练数据之外的知识，并通过引用原文降低幻觉风险。

一个标准的 RAG 流程包括文档解析、文本切片、向量化、向量检索、上下文组装和答案生成。与微调相比，RAG 的资料更新成本更低：新增或修订文档只需要重新建索引，不需要重新训练模型，而且答案可以追溯到具体来源，便于审计与纠错。

RAG 的效果上限由三件事共同决定：资料质量、检索质量和生成质量。只优化提示词而不做检索评测，通常只能解决表面问题。

实践中常见的失败可以归为三类。第一类是检索不到：正确内容根本没进候选集，通常要靠查询改写、更好的切分或更换向量模型解决。第二类是检索到了但排位靠后：正确切片落在第六到第十名，被无关内容挤掉，这类问题适合用重排序解决。第三类是检索正确但生成没用上：模型忽略了证据或过度发挥，需要从提示词、上下文组织和引用校验入手。把失败分好类，才知道该改哪一处。

## 文档切分策略

切片是检索的最小单位。切片过短容易丢失上下文，切片过长又会引入无关信息并稀释关键语义，因此切片长度与重叠范围会直接影响召回质量。

一个常用的起点是每片 700 字、重叠 100 字：700 字大约能容纳一个完整知识点，100 字重叠保证跨切片的语义不被截断。语料换成论文、代码或表格较多的文档时，需要重新调整这两个参数，并用评测确认改动是否有效。

固定窗口切分实现简单，但容易在词语或句子中间切断。结构感知切分按优先级寻找边界：先找标题，再找段落空行，再找句子结尾（中文的句号、问号、感叹号、分号与英文的句点加空格），最后才退回空格或硬切。这样能保证每个切片是一个相对完整的语义单元，也避免英文单词被切成两半。

重叠区不应该按字符硬截，而应对齐到最近的句首或行首，避免把半句话重复放入上下文。对于由多页组成的 PDF，切片通常不跨页，以保证页码可追溯。

课件与网页正文里还有一类噪声：每一页都会重复出现的页眉、页脚、页码与目录行。处理办法是统计每一行在多少页出现过，把出现率很高的行判定为版式元素并丢弃。此外，去掉空白后不足十几个字、或不含任何实词的块（例如单独的页码、装饰线条、致谢页）也应直接过滤，它们只会污染向量空间。

## 向量化与 Embedding

Embedding 把文本映射成高维向量，语义相近的文本在向量空间中距离更近，常用余弦相似度衡量接近程度。余弦相似度只关心方向不关心长度，取值在负一到一之间，实际语料里通常集中在零点几的区间。

向量的维度由模型决定，检索时必须保证查询向量与切片向量的维度一致，否则会直接报错或得到无意义的结果。更换向量模型后必须重建索引：新旧模型生成的向量不在同一语义空间，混在一起会出现「检索能跑但结果莫名其妙」的静默失败。

选择 Embedding 模型时至少要比较三点：中文或跨语言场景的表现、每批请求的条数上限、以及价格与延迟。不同厂商的兼容接口对单次批量大小有硬性限制，超出会直接返回 400 错误，例如部分模型单次最多只允许十条，因此批量参数需要按模型文档设置。

查询向量可以落盘缓存：相同模型与相同文本的向量是确定的，缓存能显著降低重复问题的检索延迟，也让重建索引更快。远程接口还应该配置超时与指数退避重试，避免接口抖动把单次检索拖到几十秒。若没有可用的模型服务，可以退化为本地哈希向量保证系统仍能运行，但哈希向量没有语义能力，只能作为离线演示的兜底。

## 向量数据库与 Qdrant

Qdrant 是面向向量检索的数据库，适合保存文本切片对应的 embedding，并通过余弦相似度寻找语义接近的内容。使用时要关注集合（Collection）的维度、距离度量、以及基于 payload 的元数据过滤——例如按课程或文档范围过滤，避免跨课程串味。

集合的维度在创建时确定，之后不能随意更改。改变向量维度或更换模型时，正确做法是换一个新的集合名称并重新入库，而不是在旧集合上强行写入。

向量库的抽象很重要：把检索接口封装成统一接口后，本地文件实现与 Qdrant 实现可以互换，业务代码不需要改动。需要注意不同实现的打分口径不同，例如本地实现常用「向量相似度与关键词覆盖率的加权和」，而 Qdrant 返回纯余弦相似度，两者的分数分布不同，切换后端后必须重新标定拒答阈值，否则可能出现全部拒答或全部放行。

## 关系型数据库与 PostgreSQL

PostgreSQL 适合保存用户、课程、文档元数据、切片索引、会话记录和任务状态，负责结构化数据与事务一致性。Qdrant 返回命中的切片标识与相似度，PostgreSQL 再提供文档名称、页码、课程归属和会话信息。

这种分工比把全部数据塞进一个数据库更容易扩展，也便于在事务里保证一致性。使用 ORM（例如 SQLAlchemy）可以让同一套模型定义适配 SQLite 与 PostgreSQL，演示阶段用 SQLite 零依赖运行，部署阶段切换连接串即可。

一个可用的最小模型包括：课程表、文档表（含原始文件名、存储路径、解析状态、切片数量与失败原因）、切片表（含所属文档、切片序号、页码与向量标识）、会话表与消息表。文档状态机建议显式设计为排队、处理中、可检索与失败四种状态，失败时把错误信息落库，便于排查而不是重跑。

## 检索策略：召回与融合

最基础的检索是向量召回：把问题向量化后，在限定范围内取相似度最高的前 k 个切片。k 越大召回率越高，但噪声也越多，常见的默认值是 5 到 10。评测时应当同时观察 Recall@k 与 NDCG@k：前者看有没有找全，后者看排得够不够靠前。

除了纯向量检索，还可以引入关键词检索。BM25 是经典的稀疏检索算法，根据词频与逆文档频率给文档打分，擅长命中专有名词、型号、代码符号等字面匹配。把向量检索与 BM25 的结果融合，常用方法是倒数排名融合（RRF）：对每个结果列表按排名计算 1/(k+排名) 并相加，再按融合分数重排，默认常数 60。

混合检索并非总是更好。当语料本身术语重复度很高（例如同一门课的课件反复出现相同名词）时，关键词信号会把大量近似切片推上来，反而挤掉正确切片；是否启用应当用评测数据决定，而不是默认打开。工程上更稳妥的做法是把开关做成配置项，用消融实验比较开启前后的 Recall 与 NDCG，再决定默认值。

## 重排序（Rerank）

重排序使用交叉编码器（Cross-Encoder）对「问题与候选切片」逐对打分，比向量相似度更能捕捉细粒度的相关性。典型流程是先召回较多候选（例如 20 条），再重排取前若干条（例如 6 条）交给模型生成。

重排序解决的是排序问题，而不是召回问题：如果正确切片压根不在候选集里，重排也救不回来。因此调优顺序应当是先保证召回（查询改写、切分质量、候选数量），再用重排提升排序质量。

重排序的代价是延迟与费用。本地部署的交叉编码器在没有 GPU 时可能带来数秒额外延迟，而 API 形式的重排通常只需一次请求。工程上应把重排当作可降级的优化：接口失败或额度耗尽时自动退回原始顺序，同时记录日志并在健康检查里暴露错误，避免静默降级。

## 查询改写（Query Rewriting）

用户的提问方式与资料写法往往不一致：口语化、省略主语、中文提问而资料是英文。查询改写用大模型把原始问题改写成更适合检索的查询，保留原意、补充同义术语，必要时补上英文关键词。

改写应当用低温度（例如 0）以保证稳定，并且一定要有回退路径：模型不可用或输出异常时使用原始问题检索。改写结果可以只用于检索，回答阶段仍使用用户的原始问题，避免改写引入的偏差影响答案表达。

跨语言场景中，查询改写带来的召回提升通常比更换 Embedding 模型更明显，也更便宜。例如中文提问去检索英文网页时，把问题扩写为包含英文术语的查询，可以让原本排在十名之外的切片回到前列；这类改动应当在评测集上量化前后差异后再上线。

## LangGraph 与 Agent 工作流

LangGraph 用来把复杂任务组织成有状态的工作流。一个课程问答 Agent 可以包含问题分析、查询改写、资料检索、相关性判断、回答生成和引用校验等节点，通过条件边决定下一步走生成还是拒绝。

状态对象在整个流程中传递，通常包含问题、检索查询、命中切片、决策结果、答案与轨迹。节点之间只通过状态通信，因此每个节点都可以单独测试与替换。条件边让分支成为一等公民：判断节点输出「生成」或「拒绝」，工作流据此路由，而不是把判断藏在提示词里。

节点化的另一个价值是可观测：运行轨迹（经过了哪些节点、检索到多少条、耗时多少）可以随答案一起返回给前端，用户能看见系统是怎么得出结论的。相比把所有逻辑写成条件分支，状态图更容易扩展多轮记忆、工具调用和重试。

## 拒答与安全边界

当检索分数低于阈值时，工作流应进入拒绝节点，明确说明资料不足，而不是让模型自由编造。拒答是 RAG 的安全边界：宁可回答「资料里没有」，也不要给出无法追溯的答案。

阈值不能凭感觉设置。正确做法是分别统计相关问题与无关问题的最高分分布，取两者之间的分界带作为阈值，并在改动后复验两类问题分别走哪条分支。实际操作中往往会出现这样的结果：无关问题的最高分明显低于相关问题的最低分，中间存在干净的分界；若没有分界，说明当前特征不足以区分，需要换手段而不是硬调阈值。

如果系统存在多种检索后端，还应针对打分口径不同的后端设定不同的兜底阈值（例如哈希向量模式使用更低阈值），否则切换后端会导致所有问题都被拒绝。阈值本身也应作为配置项，并在文档里记录它是如何标定出来的。

## 上下文组装与生成

生成阶段把命中的切片拼装成上下文。推荐给每条切片编号并附上文档名与页码，提示词要求模型只依据上下文作答、用方括号编号标注引用，并在资料不足时明确说明。

上下文不是越多越好。候选过多会稀释关键证据并增加成本，因此需要做长度预算：优先保留分数高的切片，对内容高度重复的切片去重，必要时截断过长的片段。命中数量、每片长度与最终上下文长度都应有明确上限。

温度参数应设置得较低（例如 0.1）以减少随机发挥。对话接口应返回引用列表与工作流轨迹，让用户可以展开查看原文片段，回答才能被验证而不是被相信。

## 评测体系

检索评测通常关注 Hit Rate、MRR、关键词覆盖率、答案忠实度和端到端延迟。更严格的评测会为每条用例标注标准答案切片，从而计算 Recall@K、Precision@K 与 NDCG@K：Recall 衡量该找的资料有没有找全，Precision 衡量返回里有多少是相关的，NDCG 因为带位置折扣而衡量排序质量，MRR 则只看第一个相关结果排在第几。

测试集应当包含可以直接从资料回答的问题、需要跨切片综合的问题，以及资料中确实没有答案的问题（用于测试拒答）。脚本应先校验标注是否存在、期望词是否真的出现在标注切片里，并提示可能被遗漏的相关切片，避免用错误的尺子衡量系统。

指标必须成对解读。Recall 上升而 NDCG 下降，说明资料找回来了但排序变差；两者的变化方向不一致时，不能只看其中一个就宣布优化成功。优化还应当用消融实验驱动：一次只改变一个环节，比较改动前后的指标，再决定保留还是回退。没有评测的 RAG 项目只能展示效果，无法说明系统是否稳定。

样本规模要在报告里如实说明。几十条用例、几百个切片的结果只能说明趋势，不能当作行业结论；把这句话主动说出来，比被别人问出来强得多。

## 工程化与可观测

生产化的 RAG 还需要关注：查询与向量的缓存、请求超时与重试、失败任务的错误信息落库、以及延迟的分位数统计。平均值会掩盖长尾，偶发的 20 秒请求往往来自第三方接口抖动，而不是本地检索逻辑。

配置与密钥必须和代码分离，通过环境变量注入且不进入版本库；同时要有降级策略：模型接口不可用时退化为检索式回答或离线模式，保证系统仍可演示。

流程要有可观测的轨迹与日志，出问题时能定位到是解析、检索、重排还是生成环节。健康检查除了报告服务是否存活，还应暴露关键依赖的状态（向量库、数据库、重排服务）与最近一次失败原因。

## 后续方向

常见演进路线包括：引入多轮对话的记忆与指代消解，让追问不再需要重复上下文；加入工具调用（Function Calling）让 Agent 能查询结构化数据或访问外部服务；按语料特点选择混合检索与重排的组合；以及在成本与延迟约束下做分级策略，例如简单问题走轻链路、复杂问题才启用改写与重排。
"""


def seed_demo_data() -> None:
    settings = get_settings()
    if not settings.seed_demo:
        return

    session = SessionLocal()
    try:
        if (session.scalar(select(func.count(Course.id))) or 0) > 0:
            return

        course = Course(
            name="AI 应用开发",
            description="从 RAG 到 Agent 的课程资料示例",
            color="#0F766E",
        )
        session.add(course)
        session.flush()

        sample_path = settings.upload_dir / "coursepilot-sample.md"
        sample_path.write_text(SAMPLE_COURSE, encoding="utf-8")
        document = Document(
            course_id=course.id,
            original_name="RAG 与 Agent 课程讲义.md",
            stored_path=str(sample_path),
            mime_type="text/markdown",
            status="queued",
        )
        session.add(document)
        session.commit()
        ingest_document(document.id)
    except Exception:
        session.rollback()
        logger.exception("Could not seed the demo course")
    finally:
        session.close()
